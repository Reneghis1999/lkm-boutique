const DAYS: Record<string, string> = { Lun: "Mon", Mar: "Tue", Mer: "Wed", Jeu: "Thu", Ven: "Fri", Sam: "Sat", Dim: "Sun", fermé: "closed" };
const DAY_LONG: Record<string, string> = {
  lundi: "Monday", mardi: "Tuesday", mercredi: "Wednesday", jeudi: "Thursday", vendredi: "Friday", samedi: "Saturday", dimanche: "Sunday",
};

/** Traduit un texte (sans les espaces autour) ; null si inconnu. */
export function translateEn(text: string): string | null {
  const key = text.replace(/\s+/g, " ").trim();
  if (!key) return null;
  if (EN[key] !== undefined) return EN[key];
  for (const [re, rep] of EN_PATTERNS) {
    if (re.test(key)) {
      return key.replace(re, rep).replace(/\b(lundi|mardi|mercredi|jeudi|vendredi|samedi|dimanche)\b/, (d) => DAY_LONG[d]);
    }
  }
  // Horaires : « Lun – Sam : 8h – 21h »
  if (/^(Lun|Mar|Mer|Jeu|Ven|Sam|Dim)\b.*:/.test(key)) {
    return key.replace(/\b(Lun|Mar|Mer|Jeu|Ven|Sam|Dim|fermé)\b/g, (d) => DAYS[d]).replace(" :", ":");
  }
  return null;
}
